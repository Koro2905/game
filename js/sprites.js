// Рисует 2D массив как сетку прямоугольников px×px
function drawSprite(sprite, x, y, px, pal) {
  for (let r = 0; r < sprite.length; r++) {
    for (let c = 0; c < sprite[r].length; c++) {
      const k = sprite[r][c];
      if (!k || k === " ") continue;
      ctx.fillStyle = pal[k];
      ctx.fillRect(x + c * px, y + r * px, px, px);
    }
  }
}

// Зеркальное отражение спрайта по горизонтали
function drawSpriteFlipped(sprite, x, y, px, pal) {
  const cols = sprite[0].length;
  ctx.save();
  ctx.translate(x + cols * px, 0);
  ctx.scale(-1, 1);
  drawSprite(sprite, 0, y, px, pal);
  ctx.restore();
}

